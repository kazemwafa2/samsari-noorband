export function getSystemPrompt(language: string = "fa") {
  switch (language) {
    case "en":
      return (
        SYSTEM_PROMPT +
        `

Respond in English.
`
      );

    case "ps":
      return (
        SYSTEM_PROMPT +
        `

ځواب په پښتو ژبه ورکړه.
`
      );

    case "prs":
      return (
        SYSTEM_PROMPT +
        `

پاسخ را به زبان دری افغانستان بده.
`
      );

    case "de":
      return (
        SYSTEM_PROMPT +
        `

Antworte auf Deutsch.
`
      );

    default:
      return (
        SYSTEM_PROMPT +
        `

پاسخ را به زبان فارسی/دری مناسب پیام کاربر بده.
`
      );
  }
}
