// ==================================
// GET PROMPT BY LANGUAGE + TIME
// ==================================

export function getSystemPrompt(
  language: string = "fa",
  context?: {
    timezone?: string;
    localHour?: number;
  }
) {
  const timezone = context?.timezone || "UTC";

  const localHour =
    typeof context?.localHour === "number"
      ? context.localHour
      : undefined;

  let timePeriod = "نامشخص";

  if (localHour !== undefined) {
    if (localHour >= 5 && localHour < 12) {
      timePeriod = "صبح";
    } else if (localHour >= 12 && localHour < 17) {
      timePeriod = "ظهر";
    } else if (localHour >= 17 && localHour < 21) {
      timePeriod = "عصر";
    } else {
      timePeriod = "شب";
    }
  }

  let languageInstruction = "";

  switch (language) {
    case "en":
      languageInstruction = `
Respond in English.
Use natural, friendly English.
`;
      break;

    case "ps":
      languageInstruction = `
ځواب په پښتو ژبه ورکړه.
طبیعي، درناوی کوونکی او دوستانه پښتو وکاروه.
`;
      break;

    case "prs":
      languageInstruction = `
پاسخ را به زبان دری افغانستان بده.
از واژگان طبیعی و رایج دری افغانستان استفاده کن.
`;
      break;

    case "de":
      languageInstruction = `
Antworte auf Deutsch.
Verwende natürliches, freundliches Deutsch.
`;
      break;

    default:
      languageInstruction = `
پاسخ را به زبان فارسی/دری مناسب پیام کاربر بده.
`;
      break;
  }

  return (
    SYSTEM_PROMPT +
    `

اطلاعات زمان و زبان کاربر:

زبان تشخیص‌داده‌شده سیستم: ${language}
منطقه زمانی دستگاه کاربر: ${timezone}
ساعت محلی دستگاه کاربر: ${
      localHour !== undefined ? localHour : "نامشخص"
    }
بازه زمانی فعلی: ${timePeriod}

قانون مهم:
اگر کاربر سلام یا احوال‌پرسی کرد، سلام و خوش‌آمدگویی را متناسب با همین بازه زمانی و به زبان خود کاربر انجام بده.

اگر بازه زمانی «صبح» است، می‌توانی از «صبح بخیر» استفاده کنی.
اگر «ظهر» است، می‌توانی از «ظهر بخیر» استفاده کنی.
اگر «عصر» است، می‌توانی از «عصر بخیر» استفاده کنی.
اگر «شب» است، می‌توانی از «شب بخیر» استفاده کنی.

از تکرار یک متن ثابت خودداری کن و پاسخ را طبیعی و متناسب با پیام کاربر بساز.

${languageInstruction}
`
  );
}
